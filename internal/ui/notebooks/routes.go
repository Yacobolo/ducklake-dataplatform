package notebooks

import (
	"net/http"

	"github.com/go-chi/chi/v5"
)

type Routes interface {
	ExploreList(http.ResponseWriter, *http.Request)
	ExploreFragment(http.ResponseWriter, *http.Request)
	ExploreUpdatesStream(http.ResponseWriter, *http.Request)
	ExploreUpdatesApply(http.ResponseWriter, *http.Request)
	NotebooksList(http.ResponseWriter, *http.Request)
	NotebookFoldersList(http.ResponseWriter, *http.Request)
	NotebookFoldersNew(http.ResponseWriter, *http.Request)
	NotebookFoldersCreate(http.ResponseWriter, *http.Request)
	NotebookFoldersEdit(http.ResponseWriter, *http.Request)
	NotebookFoldersUpdate(http.ResponseWriter, *http.Request)
	NotebookFoldersMove(http.ResponseWriter, *http.Request)
	NotebookFoldersDelete(http.ResponseWriter, *http.Request)
	NotebookFoldersShare(http.ResponseWriter, *http.Request)
	NotebookFoldersUnshare(http.ResponseWriter, *http.Request)
	NotebookGitReposList(http.ResponseWriter, *http.Request)
	NotebookGitReposNew(http.ResponseWriter, *http.Request)
	NotebookGitReposCreate(http.ResponseWriter, *http.Request)
	NotebookGitReposDetail(http.ResponseWriter, *http.Request)
	NotebookGitReposDelete(http.ResponseWriter, *http.Request)
	NotebookGitReposSync(http.ResponseWriter, *http.Request)
	NotebooksDetail(http.ResponseWriter, *http.Request)
	NotebookJobsList(http.ResponseWriter, *http.Request)
	NotebookJobsDetail(http.ResponseWriter, *http.Request)
	NotebooksNew(http.ResponseWriter, *http.Request)
	NotebooksCreate(http.ResponseWriter, *http.Request)
	NotebooksEdit(http.ResponseWriter, *http.Request)
	NotebooksUpdate(http.ResponseWriter, *http.Request)
	NotebooksMove(http.ResponseWriter, *http.Request)
	NotebooksMoveSubmit(http.ResponseWriter, *http.Request)
	NotebooksDuplicate(http.ResponseWriter, *http.Request)
	NotebooksDuplicateSubmit(http.ResponseWriter, *http.Request)
	NotebooksShare(http.ResponseWriter, *http.Request)
	NotebooksUnshare(http.ResponseWriter, *http.Request)
	NotebooksDelete(http.ResponseWriter, *http.Request)
	NotebookCellsNew(http.ResponseWriter, *http.Request)
	NotebookCellsCreate(http.ResponseWriter, *http.Request)
	NotebookCellsEdit(http.ResponseWriter, *http.Request)
	NotebookCellsUpdate(http.ResponseWriter, *http.Request)
	NotebookCellsRun(http.ResponseWriter, *http.Request)
	NotebookCellsMove(http.ResponseWriter, *http.Request)
	NotebookCellsDownloadCSV(http.ResponseWriter, *http.Request)
	NotebookCellsDelete(http.ResponseWriter, *http.Request)
	NotebookCellsReorder(http.ResponseWriter, *http.Request)
	NotebookRunAll(http.ResponseWriter, *http.Request)
	NotebookRunAllAsync(http.ResponseWriter, *http.Request)
	NotebookRuntimeManifest(http.ResponseWriter, *http.Request)
}

func MountRoutes(r chi.Router, h Routes) {
	r.Get("/explore", h.ExploreList)
	r.Get("/explore/", h.ExploreList)
	r.Get("/explore/fragment", h.ExploreFragment)
	r.Get("/explore/updates/{streamID}", h.ExploreUpdatesStream)
	r.Post("/explore/updates/{streamID}", h.ExploreUpdatesApply)
	r.Get("/explore/folders", h.NotebookFoldersList)
	r.Get("/explore/folders/new", h.NotebookFoldersNew)
	r.Post("/explore/folders", h.NotebookFoldersCreate)
	r.Get("/explore/folders/{folderID}/edit", h.NotebookFoldersEdit)
	r.Post("/explore/folders/{folderID}/update", h.NotebookFoldersUpdate)
	r.Post("/explore/folders/{folderID}/move", h.NotebookFoldersMove)
	r.Post("/explore/folders/{folderID}/delete", h.NotebookFoldersDelete)
	r.Post("/explore/folders/{folderID}/share", h.NotebookFoldersShare)
	r.Post("/explore/folders/{folderID}/shares/{principalName}/delete", h.NotebookFoldersUnshare)
	r.Get("/explore/git-repos", h.NotebookGitReposList)
	r.Get("/explore/git-repos/new", h.NotebookGitReposNew)
	r.Post("/explore/git-repos", h.NotebookGitReposCreate)
	r.Get("/explore/git-repos/{gitRepoID}", h.NotebookGitReposDetail)
	r.Post("/explore/git-repos/{gitRepoID}/delete", h.NotebookGitReposDelete)
	r.Post("/explore/git-repos/{gitRepoID}/sync", h.NotebookGitReposSync)
	r.Get("/notebooks", h.NotebooksList)
	r.Get("/notebooks/folders", h.NotebookFoldersList)
	r.Get("/notebooks/folders/new", h.NotebookFoldersNew)
	r.Post("/notebooks/folders", h.NotebookFoldersCreate)
	r.Get("/notebooks/folders/{folderID}/edit", h.NotebookFoldersEdit)
	r.Post("/notebooks/folders/{folderID}/update", h.NotebookFoldersUpdate)
	r.Post("/notebooks/folders/{folderID}/move", h.NotebookFoldersMove)
	r.Post("/notebooks/folders/{folderID}/delete", h.NotebookFoldersDelete)
	r.Post("/notebooks/folders/{folderID}/share", h.NotebookFoldersShare)
	r.Post("/notebooks/folders/{folderID}/shares/{principalName}/delete", h.NotebookFoldersUnshare)
	r.Get("/notebooks/git-repos", h.NotebookGitReposList)
	r.Get("/notebooks/git-repos/new", h.NotebookGitReposNew)
	r.Post("/notebooks/git-repos", h.NotebookGitReposCreate)
	r.Get("/notebooks/git-repos/{gitRepoID}", h.NotebookGitReposDetail)
	r.Post("/notebooks/git-repos/{gitRepoID}/delete", h.NotebookGitReposDelete)
	r.Post("/notebooks/git-repos/{gitRepoID}/sync", h.NotebookGitReposSync)
	r.Get("/notebooks/{notebookID}", h.NotebooksDetail)
	r.Get("/notebooks/{notebookID}/jobs", h.NotebookJobsList)
	r.Get("/notebooks/{notebookID}/jobs/{jobID}", h.NotebookJobsDetail)
	r.Get("/notebooks/new", h.NotebooksNew)
	r.Post("/notebooks", h.NotebooksCreate)
	r.Get("/notebooks/{notebookID}/edit", h.NotebooksEdit)
	r.Post("/notebooks/{notebookID}/update", h.NotebooksUpdate)
	r.Get("/notebooks/{notebookID}/move", h.NotebooksMove)
	r.Post("/notebooks/{notebookID}/move", h.NotebooksMoveSubmit)
	r.Get("/notebooks/{notebookID}/duplicate", h.NotebooksDuplicate)
	r.Post("/notebooks/{notebookID}/duplicate", h.NotebooksDuplicateSubmit)
	r.Post("/notebooks/{notebookID}/share", h.NotebooksShare)
	r.Post("/notebooks/{notebookID}/shares/{principalName}/delete", h.NotebooksUnshare)
	r.Post("/notebooks/{notebookID}/delete", h.NotebooksDelete)
	r.Get("/notebooks/{notebookID}/cells/new", h.NotebookCellsNew)
	r.Post("/notebooks/{notebookID}/cells", h.NotebookCellsCreate)
	r.Get("/notebooks/{notebookID}/cells/{cellID}/edit", h.NotebookCellsEdit)
	r.Post("/notebooks/{notebookID}/cells/{cellID}/update", h.NotebookCellsUpdate)
	r.Post("/notebooks/{notebookID}/cells/{cellID}/run", h.NotebookCellsRun)
	r.Post("/notebooks/{notebookID}/cells/{cellID}/move", h.NotebookCellsMove)
	r.Get("/notebooks/{notebookID}/cells/{cellID}/download.csv", h.NotebookCellsDownloadCSV)
	r.Post("/notebooks/{notebookID}/cells/{cellID}/delete", h.NotebookCellsDelete)
	r.Post("/notebooks/{notebookID}/cells/reorder", h.NotebookCellsReorder)
	r.Post("/notebooks/{notebookID}/run-all", h.NotebookRunAll)
	r.Post("/notebooks/{notebookID}/run-all-async", h.NotebookRunAllAsync)
	r.Get("/notebooks/runtime/manifest", h.NotebookRuntimeManifest)
}
