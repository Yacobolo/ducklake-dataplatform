func exportedName(operationID string) string {
	parts := splitIdentifier(operationID)
	if len(parts) == 0 {
		return "Operation"
	}
	for i := range parts {
		parts[i] = strings.ToUpper(parts[i][:1]) + parts[i][1:]
	}
	return strings.Join(parts, "")
}

func splitIdentifier(value string) []string {
	value = strings.TrimSpace(value)
	if value == "" {
		return nil
	}
	replacer := strings.NewReplacer("-", " ", "_", " ", ".", " ", "/", " ")
	value = replacer.Replace(value)
	chunks := strings.Fields(value)
	if len(chunks) > 0 {
		return chunks
	}
	return []string{value}
}

func collectCloneSet(rootNames []string, typesByName map[string]*ast.TypeSpec) map[string]struct{} {
	cloneSet := make(map[string]struct{})
	queue := append([]string(nil), rootNames...)

	for len(queue) > 0 {
		name := queue[0]
		queue = queue[1:]
		if _, seen := cloneSet[name]; seen {
			continue
		}
		spec, ok := typesByName[name]
		if !ok {
			continue
		}
		structType, ok := spec.Type.(*ast.StructType)
		if !ok {
			continue
		}
		cloneSet[name] = struct{}{}
		for _, depName := range referencedCloneableTypes(structType, typesByName) {
			queue = append(queue, depName)
		}
	}

	return cloneSet
}

func referencedCloneableTypes(structType *ast.StructType, typesByName map[string]*ast.TypeSpec) []string {
	seen := make(map[string]struct{})
	ast.Inspect(structType, func(node ast.Node) bool {
		ident, ok := node.(*ast.Ident)
		if !ok {
			return true
		}
		spec, ok := typesByName[ident.Name]
		if !ok {
			return true
		}
		if _, ok := spec.Type.(*ast.StructType); ok {
			seen[ident.Name] = struct{}{}
		}
		return true
	})

	names := make([]string, 0, len(seen))
	for name := range seen {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}

func renderClonedStruct(name string, structType *ast.StructType, cloneSet map[string]struct{}) string {
	var b strings.Builder
	b.WriteString("type ")
	b.WriteString(name)
	b.WriteString(" struct {\n")
	for _, field := range structType.Fields.List {
		if len(field.Names) == 0 {
			b.WriteString("\t")
			b.WriteString(renderExpr(rewriteExpr(field.Type, cloneSet)))
			if field.Tag != nil {
				b.WriteString(" ")
				b.WriteString(field.Tag.Value)
			}
			b.WriteString("\n")
			continue
		}
		for i, fieldName := range field.Names {
			if i == 0 {
				b.WriteString("\t")
			} else {
				b.WriteString(", ")
			}
			b.WriteString(fieldName.Name)
		}
		b.WriteString(" ")
		b.WriteString(renderExpr(rewriteExpr(field.Type, cloneSet)))
		if field.Tag != nil {
			b.WriteString(" ")
			b.WriteString(field.Tag.Value)
		}
		b.WriteString("\n")
	}
	b.WriteString("}\n\n")
	return b.String()
}

func rewriteExpr(expr ast.Expr, cloneSet map[string]struct{}) ast.Expr {
	switch e := expr.(type) {
	case *ast.Ident:
		if _, ok := cloneSet[e.Name]; ok {
			return ast.NewIdent(genSchemaTypeName(e.Name))
		}
		return ast.NewIdent(e.Name)
	case *ast.StarExpr:
		return &ast.StarExpr{X: rewriteExpr(e.X, cloneSet)}
	case *ast.ArrayType:
		return &ast.ArrayType{Len: e.Len, Elt: rewriteExpr(e.Elt, cloneSet)}
	case *ast.MapType:
		return &ast.MapType{Key: rewriteExpr(e.Key, cloneSet), Value: rewriteExpr(e.Value, cloneSet)}
	case *ast.SelectorExpr:
		return &ast.SelectorExpr{X: rewriteExpr(e.X, cloneSet), Sel: ast.NewIdent(e.Sel.Name)}
	case *ast.InterfaceType:
		return &ast.InterfaceType{Methods: e.Methods, Incomplete: e.Incomplete}
	default:
		return e
	}
}

func renderExpr(expr ast.Expr) string {
	var buf bytes.Buffer
	_ = printer.Fprint(&buf, token.NewFileSet(), expr)
	return buf.String()
}

func structUsesTime(structType *ast.StructType, cloneSet map[string]struct{}) bool {
	for _, field := range structType.Fields.List {
		if containsClonedTimeRef(rewriteExpr(field.Type, cloneSet)) {
			return true
		}
	}
	return false
}

func containsClonedTimeRef(expr ast.Expr) bool {
	usesTime := false
	ast.Inspect(expr, func(node ast.Node) bool {
		selector, ok := node.(*ast.SelectorExpr)
		if !ok {
			return true
		}
		ident, ok := selector.X.(*ast.Ident)
		if ok && ident.Name == "time" && selector.Sel.Name == "Time" {
			usesTime = true
			return false
		}
		return true
	})
	return usesTime
}

func genSchemaTypeName(name string) string {
	return "GenSchema" + name
}

func contains(values []string, target string) bool {
	for _, value := range values {
		if value == target {
			return true
		}
	}
	return false
}
