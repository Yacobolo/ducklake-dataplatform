// Package requestmodelgo emits APIGen-owned schema model clones from legacy oapi types.
package requestmodelgo

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/parser"
	"go/printer"
	"go/token"
	"sort"
	"strings"

	"duck-demo/internal/apigen/ir"
)

// Emit renders APIGen-owned request schema types derived from legacy oapi models.
func Emit(doc ir.Document, legacyTypesPath string) ([]byte, error) {
	return emit(doc, legacyTypesPath)
}

// EmitWithResponseRoots renders APIGen-owned request and safe response schema
// types using IR-declared response schemas.
func EmitWithResponseRoots(doc ir.Document, legacyTypesPath string) ([]byte, error) {
	return emit(doc, legacyTypesPath)
}

func emit(doc ir.Document, legacyTypesPath string) ([]byte, error) {
	typesByName, err := loadLegacyTypes(legacyTypesPath)
	if err != nil {
		return nil, err
	}

	rootNames, err := schemaRoots(doc)
	if err != nil {
		return nil, err
	}
	cloneSet := collectCloneSet(rootNames, typesByName)

	allNames := make([]string, 0, len(cloneSet))
	for name := range cloneSet {
		allNames = append(allNames, name)
	}
	sort.Strings(allNames)

	usesTime := false
	for _, name := range allNames {
		if structType, ok := typesByName[name].Type.(*ast.StructType); ok && structUsesTime(structType, cloneSet) {
			usesTime = true
			break
		}
	}

	var b strings.Builder
	b.WriteString("// Code generated by apigen schema model emitter. DO NOT EDIT.\n")
	b.WriteString("package api\n\n")
	if usesTime {
		b.WriteString("import \"time\"\n\n")
	}

	for _, rootName := range rootNames {
		spec, ok := typesByName[rootName]
		if !ok {
			return nil, fmt.Errorf("request model %q not found in %s", rootName, legacyTypesPath)
		}
		if _, isCloned := cloneSet[rootName]; isCloned {
			b.WriteString(renderClonedStruct(genSchemaTypeName(rootName), spec.Type.(*ast.StructType), cloneSet))
			continue
		}
		b.WriteString("type ")
		b.WriteString(genSchemaTypeName(rootName))
		b.WriteString(" = ")
		b.WriteString(rootName)
		b.WriteString("\n\n")
	}

	for _, name := range allNames {
		if contains(rootNames, name) {
			continue
		}
		b.WriteString(renderClonedStruct(genSchemaTypeName(name), typesByName[name].Type.(*ast.StructType), cloneSet))
	}

	return []byte(b.String()), nil
}

func schemaRoots(doc ir.Document) ([]string, error) {
	seen := make(map[string]struct{})
	for _, name := range requestSchemaRoots(doc) {
		seen[name] = struct{}{}
	}

	for _, name := range safeResponseSchemaRoots(doc) {
		seen[name] = struct{}{}
	}

	rootNames := make([]string, 0, len(seen))
	for name := range seen {
		rootNames = append(rootNames, name)
	}
	sort.Strings(rootNames)
	return rootNames, nil
}

func loadLegacyTypes(path string) (map[string]*ast.TypeSpec, error) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
	if err != nil {
		return nil, fmt.Errorf("parse legacy request models: %w", err)
	}

	typesByName := make(map[string]*ast.TypeSpec)
	for _, decl := range file.Decls {
		genDecl, ok := decl.(*ast.GenDecl)
		if !ok || genDecl.Tok != token.TYPE {
			continue
		}
		for _, spec := range genDecl.Specs {
			typeSpec, ok := spec.(*ast.TypeSpec)
			if !ok {
				continue
			}
			typesByName[typeSpec.Name.Name] = typeSpec
		}
	}

	return typesByName, nil
}

func requestSchemaRoots(doc ir.Document) []string {
	seen := make(map[string]struct{})
	for _, endpoint := range doc.Endpoints {
		if endpoint.RequestBody == nil {
			continue
		}
		if schemaName, ok := resolveRequestSchemaName(doc, endpoint); ok {
			seen[schemaName] = struct{}{}
		}
	}

	rootNames := make([]string, 0, len(seen))
	for name := range seen {
		rootNames = append(rootNames, name)
	}
	sort.Strings(rootNames)
	return rootNames
}

func safeResponseSchemaRoots(doc ir.Document) []string {
	seen := make(map[string]struct{})
	for _, endpoint := range doc.Endpoints {
		for _, response := range endpoint.Responses {
			if shape, ok, err := ir.ResponseShapeMetadata(response); err == nil && ok {
				if shape.BodyType != "" {
					seen[shape.BodyType] = struct{}{}
				}
				continue
			}
			if response.Schema == nil || isErrorSchemaRef(*response.Schema) {
				continue
			}
			bodyTypeName, ok := normalizedSchemaRefName(*response.Schema)
			if !ok {
				continue
			}
			seen[bodyTypeName] = struct{}{}
		}
	}

	rootNames := make([]string, 0, len(seen))
	for name := range seen {
		rootNames = append(rootNames, name)
	}
	sort.Strings(rootNames)
	return rootNames
}

func normalizedSchemaRefName(schema ir.SchemaRef) (string, bool) {
	if schema.Ref == "" {
		return "", false
	}
	ref := strings.TrimSpace(schema.Ref)
	ref = strings.TrimPrefix(ref, "#/components/schemas/")
	ref = strings.TrimPrefix(ref, "#/schemas/")
	if idx := strings.LastIndex(ref, "/"); idx >= 0 {
		ref = ref[idx+1:]
	}
	if ref == "" {
		return "", false
	}
	return ref, true
}

func isErrorSchemaRef(schema ir.SchemaRef) bool {
	ref, ok := normalizedSchemaRefName(schema)
	if !ok {
		return false
	}
	return exportedName(ref) == "Error"
}

func resolveRequestSchemaName(doc ir.Document, endpoint ir.Endpoint) (string, bool) {
	if endpoint.RequestBody == nil {
		return "", false
	}

	schema := endpoint.RequestBody.Schema
	if schema.Ref != "" && schema.Ref != "GenericRequest" {
		return schema.Ref, true
	}
	if schema.Ref == "GenericRequest" {
		if schemaName, ok := resolveGenericRequestBodySchemaName(doc, endpoint.OperationID); ok {
			return schemaName, true
		}
	}
	return "", false
}

func resolveGenericRequestBodySchemaName(doc ir.Document, operationID string) (string, bool) {
	if schemaName, ok := genericRequestBodySchemaOverrides[operationID]; ok {
		return schemaName, true
	}
	for _, candidate := range genericRequestBodySchemaCandidates(operationID) {
		if _, ok := doc.Schemas[candidate]; ok {
			return candidate, true
		}
	}
	return "", false
}

func genericRequestBodySchemaCandidates(operationID string) []string {
	return []string{exportedName(operationID) + "Request"}
}

